"""Emit rtl/grand_piano_norm.svh -- the one string table the RTL cannot build.

Every other string coefficient is now computed inside the RTL at elaboration
by `grand_piano_string_roms.svh`.  This one is not, for a practical reason:
the per-note loudness scaling is `note_loudness / peak`, and finding the peak
means summing every component of the note across the first 300 ms.  That is
481 million sin-and-exp evaluations across the compass -- seconds in a
compiled simulator, hours in an interpreted elaborator.

So it stays a table: 352 numbers, against the 69,496 the RTL now generates
for itself.
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

import hw_model as hw       # noqa: E402
import piano_physics as phys  # noqa: E402


def norm_scale(pitch, velocity, comps, sample_rate=hw.SAMPLE_RATE):
    """note_loudness / peak, the factor normalised_amplitudes() applies."""
    amps = hw.amplitudes(pitch, velocity, comps, sample_rate)
    if not len(amps) or amps.max() <= 0:
        return 1.0
    span = int(0.3 * sample_rate)
    t = np.arange(span) / sample_rate
    total = np.zeros(span)
    for (freq, rate, phase, _, _, _), amp in zip(comps, amps):
        if amp <= 0.0:
            continue
        total += amp * np.exp(-rate * t) * np.sin(2 * np.pi * freq * t + phase)
    peak = float(np.abs(total).max())
    if peak <= 0.0:
        return 1.0
    return hw.note_loudness(pitch, velocity) / peak


def main():
    rows = []
    for pitch in range(phys.LOWEST_MIDI, phys.HIGHEST_MIDI + 1):
        comps = hw.components(pitch)
        rows.append([norm_scale(pitch, hw.velocity_for_layer(v), comps)
                     for v in range(hw.VELOCITY_LAYERS)])

    out = ["// Generated by tools/gen_norm_table.py -- do not edit.",
           "//",
           "// Per-note, per-velocity-layer output scaling: note_loudness",
           "// divided by the peak of the summed note over its first 300 ms.",
           "// See the module docstring in the generator for why this one",
           "// table is not computed at elaboration like the rest.",
           "`ifndef GRAND_PIANO_NORM_SVH",
           "`define GRAND_PIANO_NORM_SVH",
           "",
           f"localparam real NOTE_NORM [0:{len(rows) - 1}]"
           f"[0:{hw.VELOCITY_LAYERS - 1}] = '{{"]
    for i, row in enumerate(rows):
        pitch = phys.LOWEST_MIDI + i
        body = ", ".join(f"{v:.17g}" for v in row)
        comma = "," if i < len(rows) - 1 else ""
        out.append(f"  '{{{body}}}{comma}   // MIDI {pitch}")
    out += ["};", "", "`endif", ""]

    path = ROOT / "rtl" / "grand_piano_norm.svh"
    path.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {path}  ({len(rows)} notes x {hw.VELOCITY_LAYERS} layers)")


if __name__ == "__main__":
    main()
