"""Emit rtl/grand_piano_body.svh -- the FEA soundboard modes, as literals.

The soundboard is the one part of the instrument that is not a closed-form
equation.  `soundboard_fea.py` assembles an orthotropic Kirchhoff plate by
finite differences and solves a sparse shift-invert eigenproblem for its
modes; nothing about that belongs in an elaboration-time function.

So its 64 quantised numbers are written here as literals.  With this table
and the 352 loudness scalars, the RTL derives every one of its remaining
69,496 coefficients for itself.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

import hw_model as hw   # noqa: E402


def main():
    rows = hw.body_rom()
    names = ("BODY_K_Q", "BODY_LOSS_Q", "BODY_GL_Q", "BODY_GR_Q")

    out = ["// Generated by tools/gen_body_table.py -- do not edit.",
           "//",
           "// Soundboard modes from the finite-element solve in",
           "// tools/soundboard_fea.py: an orthotropic spruce plate, assembled",
           "// from strain energy so the stiffness matrix stays symmetric, then",
           "// a sparse shift-invert eigensolve.  Quantised once and held here",
           "// because a sparse eigensolve is not an elaboration-time function.",
           "`ifndef GRAND_PIANO_BODY_SVH",
           "`define GRAND_PIANO_BODY_SVH",
           ""]
    for col, name in enumerate(names):
        values = ", ".join(str(r[col]) for r in rows)
        out.append(f"localparam longint {name} [0:{len(rows) - 1}] = "
                   f"'{{{values}}};")
    out += ["", "`endif", ""]

    path = ROOT / "rtl" / "grand_piano_body.svh"
    path.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {path}  ({len(rows)} modes x {len(names)} values)")


if __name__ == "__main__":
    main()
